"""Make sure that the generated ``baml_sdk`` package exists and matches the installed ``baml-bridge``.

``baml_sdk`` is gitignored. ``baml generate`` writes it from ``baml_src/``. In a source checkout, ``ensure_sdk`` runs
that command when the package is missing. When the package was generated by another BAML toolchain than the one that
``baml-bridge`` expects (a version skew), it selects the expected toolchain and generates the package again. If it
cannot fix the cause, it raises ``SDKUnavailableError`` with the steps that do.
"""

import importlib
import importlib.util
import re
import shutil
import subprocess  # ruff: ignore[suspicious-subprocess-import] -- the only calls run the baml binary with fixed arguments
import sys
from collections.abc import Sequence
from pathlib import Path

import structlog

from ebaml.core.exceptions import SDKUnavailableError

logger: structlog.typing.FilteringBoundLogger = structlog.get_logger(__name__)

SDK_NAME = "baml_sdk"
_INSTALL_COMMAND = "curl -fsSL https://pkg.boundaryml.com/install.sh | sh -s"
_COMMAND_TIMEOUT_SECONDS = 300
_OUTPUT_LINES = 15
_SKEW_MARK = "version skew"
# `baml` refuses to run when the agent skill that it installed for AI coding agents belongs to another toolchain. The
# check has nothing to do with code generation, and the error itself names the flag that turns it off.
_SKILL_MARK = "agent skill"
_SKILL_OFF = ("--agent-skill-check", "off")
# The start-up error of a skewed SDK ends one sentence with the version that baml-bridge expects.
_EXPECTED_TOOLCHAIN = re.compile(r"expects baml_sdk to be generated using BAML toolchain (\d+(?:\.\d+)+)")


def _project_root(start: Path) -> Path | None:
    """Find the source checkout that holds ``baml.toml`` and ``baml_src/``.

    Parameters
    ----------
    start : Path
        A file or directory inside the checkout.

    Returns
    -------
    Path | None
        The root of the checkout, or ``None`` if ``start`` is not inside one (an installed package).

    """
    for directory in start.resolve().parents:
        if (directory / "baml.toml").is_file() and (directory / "baml_src").is_dir():
            return directory
    return None


def _find_baml(home: Path) -> str | None:
    """Find the ``baml`` command.

    The installer puts ``baml`` in ``~/.baml/bin``. A shell that did not load the profile line of the installer does not
    have that directory on ``PATH``, so the search looks there too.

    Parameters
    ----------
    home : Path
        The home directory of the user.

    Returns
    -------
    str | None
        The path of the command, or ``None`` if there is none.

    """
    on_path = shutil.which("baml")
    if on_path is not None:
        return on_path
    installed = home / ".baml" / "bin" / "baml"
    return str(installed) if installed.is_file() else None


def _tail(text: str) -> str:
    """Keep the last lines of the output of a command, with an indent.

    Parameters
    ----------
    text : str
        The output.

    Returns
    -------
    str
        The last lines, one indented line each, or ``"  (no output)"`` for an empty output.

    """
    lines = text.strip().splitlines()[-_OUTPUT_LINES:]
    return "\n".join(f"  {line}" for line in lines) or "  (no output)"


def _steps(root: Path | None, *, with_install: bool, commands: Sequence[str] = ("baml generate",)) -> str:
    """Write the steps that make ``baml_sdk`` importable.

    Parameters
    ----------
    root : Path | None
        The source checkout, or ``None`` for an installed package.
    with_install : bool
        Whether the BAML toolchain is missing, so the steps start with its installation.
    commands : Sequence[str]
        The commands to run in the checkout, in order.

    Returns
    -------
    str
        A numbered list of steps.

    """
    if root is None:
        return (
            "This copy of ebaml is installed without its source checkout, and a release must contain baml_sdk.\n"
            "  1. Reinstall ebaml from a release file.\n"
            "  2. To build from source, run `baml generate` in the checkout before `uv build`."
        )
    steps = []
    if with_install:
        steps += [
            f"Install the BAML toolchain: {_INSTALL_COMMAND}",
            'Open a new shell, or run `. "$HOME/.baml/env"`, so that `baml` is on PATH.',
        ]
    steps += [
        "Check that `baml --version` prints 0.23 or later. If it is older, put ~/.baml/bin first on PATH.",
        *(f"Run `{command}` in {root}." for command in commands),
    ]
    return "\n".join(f"  {number}. {step}" for number, step in enumerate(steps, start=1))


def _run(command: Sequence[str], root: Path, problem: str, steps: str) -> None:
    """Run a ``baml`` command in the checkout.

    Parameters
    ----------
    command : Sequence[str]
        The path of the ``baml`` command and its arguments.
    root : Path
        The source checkout.
    problem : str
        The first words of the error message: what is wrong with ``baml_sdk``.
    steps : str
        The steps that the error message gives to fix the cause by hand.

    Raises
    ------
    SDKUnavailableError
        If the command cannot start, times out, or exits with an error. The message has the end of its output. A
        command that fails on the agent skill check runs once more with the check off.

    """
    shown = " ".join(command)
    logger.info("sdk_command", command=shown, cwd=str(root))
    try:
        done = subprocess.run(  # ruff: ignore[subprocess-without-shell-equals-true] -- the command is the baml binary that the lookup found, with fixed arguments
            list(command),
            cwd=root,
            capture_output=True,
            text=True,
            timeout=_COMMAND_TIMEOUT_SECONDS,
            check=False,
        )
    except (OSError, subprocess.TimeoutExpired) as error:
        message = f"{problem}, and `{shown}` did not finish: {error}.\nTo fix it:\n{steps}"
        raise SDKUnavailableError(message) from error
    output = done.stderr or done.stdout
    if done.returncode != 0 and _SKILL_MARK in output and _SKILL_OFF[0] not in command:
        logger.info("sdk_skill_check_off", command=shown)
        _run([*command, *_SKILL_OFF], root, problem, steps)
        return
    if done.returncode != 0:
        message = (
            f"{problem}, and `{shown}` failed with exit code {done.returncode}. Its output ends:\n"
            f"{_tail(output)}\n"
            f"To fix it:\n{steps}"
        )
        raise SDKUnavailableError(message)


def _generate_missing(start: Path, home: Path) -> Path:
    """Generate the missing ``baml_sdk`` package in the checkout.

    Parameters
    ----------
    start : Path
        A path inside the checkout.
    home : Path
        The home directory in which to look for the ``baml`` command.

    Returns
    -------
    Path
        The root of the checkout.

    Raises
    ------
    SDKUnavailableError
        If there is no checkout, no ``baml`` command, or the command fails.

    """
    root = _project_root(start)
    if root is None:
        message = f"{SDK_NAME} is missing.\n{_steps(None, with_install=False)}"
        raise SDKUnavailableError(message)
    baml = _find_baml(home)
    if baml is None:
        message = (
            f"{SDK_NAME} is missing, and ebaml cannot generate it because the `baml` command was not found.\n"
            f"To fix it:\n{_steps(root, with_install=True)}"
        )
        raise SDKUnavailableError(message)
    _run([baml, "generate"], root, f"{SDK_NAME} is missing", _steps(root, with_install=False))
    importlib.invalidate_caches()
    if importlib.util.find_spec(SDK_NAME) is None:
        message = (
            f"`{baml} generate` finished, but {SDK_NAME} is still not importable. `baml generate` writes it to the "
            f"`output_dir` of {root / 'baml.toml'}, and that directory must be on sys.path.\n"
            f"To fix it, install the project in this environment with `uv sync` in {root}."
        )
        raise SDKUnavailableError(message)
    logger.info("sdk_generated", root=str(root))
    return root


def _forget_sdk(package: str) -> None:
    """Remove a package and its submodules from the module cache, so that the next import reads the new files.

    Parameters
    ----------
    package : str
        The name of the package.

    """
    for name in [name for name in sys.modules if name == package or name.startswith(f"{package}.")]:
        del sys.modules[name]
    importlib.invalidate_caches()


def _repair_skew(error: RuntimeError, root: Path | None, home: Path) -> None:
    """Select the BAML toolchain that ``baml-bridge`` expects, generate ``baml_sdk`` again, and import it.

    Parameters
    ----------
    error : RuntimeError
        The start-up error of the skewed SDK. Its text names the expected toolchain.
    root : Path | None
        The source checkout, or ``None`` for an installed package.
    home : Path
        The home directory in which to look for the ``baml`` command.

    Raises
    ------
    SDKUnavailableError
        If the cause is outside a checkout, the expected version or the ``baml`` command is missing, a command fails,
        or the versions still differ after the repair.

    """
    expected = _EXPECTED_TOOLCHAIN.search(str(error))
    if root is None or expected is None:
        message = (
            f"{error}\n\nThe generated {SDK_NAME} and baml-bridge need the same BAML toolchain version.\n"
            "To fix it, reinstall ebaml and baml-bridge together from the same release."
        )
        raise SDKUnavailableError(message) from error
    version = expected.group(1)
    commands = (f"baml toolchain use {version}", "baml generate")
    steps = _steps(root, with_install=False, commands=commands)
    problem = f"{SDK_NAME} was generated by another BAML toolchain than baml-bridge expects ({version})"
    baml = _find_baml(home)
    if baml is None:
        message = (
            f"{problem}, and ebaml cannot repair it because the `baml` command was not found.\n"
            f"To fix it:\n{_steps(root, with_install=True, commands=commands)}"
        )
        raise SDKUnavailableError(message) from error
    _run([baml, "toolchain", "use", version], root, problem, steps)
    _run([baml, "generate"], root, problem, steps)
    _forget_sdk(SDK_NAME)
    try:
        importlib.import_module(SDK_NAME)
    except RuntimeError as again:
        message = (
            f"{again}\n\nebaml ran `baml toolchain use {version}` and `baml generate`, but the versions still differ.\n"
            f"To fix it, check that the `baml.toml` in {root} does not pin another toolchain "
            f"(`baml toolchain pin {version}` pins this one), then run `baml generate`."
        )
        raise SDKUnavailableError(message) from again
    logger.info("sdk_repaired", toolchain=version)


def ensure_sdk(*, start: Path | None = None, home: Path | None = None) -> None:
    """Make ``baml_sdk`` importable: generate it if it is missing, and repair a version skew.

    The function does nothing more than import the package when the package exists and works. Call it before the first
    ``import baml_sdk``.

    Parameters
    ----------
    start : Path | None
        A path inside the checkout to search from. ``None`` selects this module.
    home : Path | None
        The home directory in which to look for the ``baml`` command. ``None`` selects the home directory of the user.

    If the package is missing or skewed and the function cannot fix it, ``SDKUnavailableError`` lists the steps that
    fix the cause.

    Raises
    ------
    RuntimeError
        If the package fails to start for a reason other than a version skew.

    """
    start = start or Path(__file__)
    home = home or Path.home()
    root = None if importlib.util.find_spec(SDK_NAME) is not None else _generate_missing(start, home)
    try:
        importlib.import_module(SDK_NAME)
    except RuntimeError as error:
        if _SKEW_MARK not in str(error):
            raise
        _repair_skew(error, root or _project_root(start), home)
